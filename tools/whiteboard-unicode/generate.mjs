// Generate Unicode property intervals from the pinned UCD, not from host ICU.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join, resolve } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const data = join(here, 'data/17.0.0');
const limit = 0x110000;
const read = name => readFileSync(join(data, name), 'utf8');

function properties(name, initial) {
    const values = Array(limit).fill(initial);
    const lines = read(name).split(/\r?\n/);
    const apply = (range, value) => {
        const [first, last = first] = range.trim().split('..').map(x => parseInt(x, 16));
        const aliases = { Left_To_Right: 'L', Right_To_Left: 'R', Arabic_Letter: 'AL', European_Terminator: 'ET' };
        const property = value.trim();
        values.fill(aliases[property] ?? property, first, last + 1);
    };
    for (const line of lines) {
        const match = line.match(/^#\s*@missing:\s*([^;]+);\s*([^#]+)/);
        if (match) apply(match[1], match[2]);
    }
    for (const line of lines) {
        const fields = line.split('#')[0].split(';');
        if (fields.length >= 2 && fields[0].trim()) apply(fields[0], fields[1]);
    }
    return values;
}

function categories() {
    const values = Array(limit).fill('Cn');
    let first = 0;
    for (const line of read('UnicodeData.txt').split(/\r?\n/)) {
        const fields = line.split(';');
        if (fields.length < 3) continue;
        const cp = parseInt(fields[0], 16);
        if (fields[1].endsWith(', First>')) first = cp;
        else if (fields[1].endsWith(', Last>')) values.fill(fields[2], first, cp + 1);
        else values[cp] = fields[2];
    }
    return values;
}

function encode(values) {
    const names = [...new Set(values)].sort();
    const ids = new Map(names.map((value, index) => [value, index]));
    const intervals = [];
    for (let i = 0; i < limit;) {
        const value = values[i];
        let end = i + 1;
        while (end < limit && values[end] === value) end++;
        intervals.push(i, end - 1, ids.get(value));
        i = end;
    }
    return { names, intervals };
}

const tables = {
    lineBreak: encode(properties('LineBreak.txt', 'XX')),
    bidiClass: encode(properties('extracted/DerivedBidiClass.txt', 'Left_To_Right')),
    eastAsianWidth: encode(properties('EastAsianWidth.txt', 'N')),
    category: encode(categories()),
};
// emoji-data contains overlapping properties: retain Extended_Pictographic only.
const emoji = Array(limit).fill('N');
for (const line of read('emoji/emoji-data.txt').split(/\r?\n/)) {
    const fields = line.split('#')[0].split(';').map(s => s.trim());
    if (fields[1] !== 'Extended_Pictographic') continue;
    const [first, last = first] = fields[0].split('..').map(x => parseInt(x, 16));
    emoji.fill('Y', first, last + 1);
}
tables.extendedPictographic = encode(emoji);
const brackets = [];
for (const line of read('BidiBrackets.txt').split(/\r?\n/)) {
    const fields = line.split('#')[0].split(';').map(s => s.trim());
    if (fields.length < 3) continue;
    brackets.push(parseInt(fields[0], 16), parseInt(fields[1], 16), fields[2] === 'o' ? 1 : 0);
}
const output = `// Generated by tools/whiteboard-unicode/generate.mjs from Unicode 17.0.0; do not edit.\n`
    + `export const UNICODE_VERSION = '17.0.0';\n`
    + `export const unicodeTables: Readonly<Record<string, { readonly names: readonly string[]; readonly intervals: readonly number[] }>> = ${JSON.stringify(tables)};\n`
    + `export const bidiBrackets: readonly number[] = ${JSON.stringify(brackets)};\n`;
writeFileSync(resolve(here, '../../src/whiteboard/text/unicodeTables.ts'), output);
